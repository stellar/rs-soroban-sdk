// See soroban-sdk/docs/contracttrait.md for documentation on how this works.

#[derive(Debug, FromMeta)]
struct Args {
    #[darling(default = "default_crate_path")]
    crate_path: Path,
    trait_ident: Path,
    // Absent in trait macros generated by SDK versions that did not capture the
    // types of default fns, in which case the fns contain no placeholders.
    trait_name: Option<String>,
    trait_default_fns: Vec<LitStr>,
    impl_ident: Ident,
    impl_fns: Vec<LitStr>,
    client_name: String,
    args_name: String,
    spec_name: Type,
    spec_export: Option<bool>,
}

pub fn derive_contractimpl_trait_default_fns_not_overridden(
    metadata: TokenStream2,
) -> TokenStream2 {
    match derive_or_err(metadata) {
        Ok(tokens) => tokens,
        Err(err) => err.write_errors(),
    }
}

fn derive_or_err(metadata: TokenStream2) -> Result<TokenStream2, Error> {
    let args = NestedMeta::parse_meta_list(metadata.into())?;
    let args = Args::from_list(&args)?;
    let derived = derive(&args)?;
    Ok(quote! {
        #derived
    }
    .into())
}

fn derive(args: &Args) -> Result<TokenStream2, Error> {
    let impl_ty = ident_to_type(args.impl_ident.clone());
    let trait_ident = &args.trait_ident;
    let spec_export = args.spec_export.unwrap_or(true);

    let trait_default_fns = syn_ext::strs_to_fns(&args.trait_default_fns)?;
    let impl_fns = syn_ext::strs_to_fns(&args.impl_fns)?;

    // Filter the list of default fns down to only default fns that have not been redefined /
    // overridden in the input fns.
    let fns = trait_default_fns
        .into_iter()
        .filter_map(|mut f| {
            let matching_impl_fns = impl_fns
                .iter()
                .filter(|impl_fn| impl_fn.ident.unraw() == f.ident.unraw())
                .collect::<Vec<_>>();
            if matching_impl_fns.is_empty() {
                return Some(Ok(f));
            }

            for impl_fn in matching_impl_fns {
                match cfg_condition(&impl_fn.attrs) {
                    Ok(Some(cfg)) => {
                        f.attrs.push(syn::parse_quote!(#[cfg(not(#cfg))]));
                    }
                    Ok(None) => return None,
                    Err(err) => return Some(Err(err)),
                }
            }

            Some(Ok(f))
        })
        .collect::<Result<Vec<_>, Error>>()?;

    // With no default fns left there is nothing to generate, and the empty
    // registration ctor would otherwise clash with an empty impl's own.
    if fns.is_empty() {
        return Ok(quote! {});
    }

    // Replace the placeholders for types captured where the trait is defined
    // with those types, named through aliases in a module local to the impl.
    // Each alias projects the type through a trait local to the impl from the
    // hidden supertraits that capture it. The aliases have the names of the
    // types, so that docs show the type's name rather than the projection.
    let impl_name = args.impl_ident.unraw();
    let trait_name = args.trait_name.as_deref().unwrap_or_default();
    let local_ident = format_ident!("__{impl_name}_{trait_name}_project");
    let types_ident = format_ident!("__{impl_name}_{trait_name}_types");
    let mut replacer = ReplaceTypePlaceholders {
        local: quote!(#types_ident),
        names: Vec::new(),
    };
    let mut fns = fns;
    for f in &mut fns {
        for input in f.inputs.iter_mut() {
            if let FnArg::Typed(pat_type) = input {
                replacer.visit_type_mut(&mut pat_type.ty);
            }
        }
        if let ReturnType::Type(_, ty) = &mut f.output {
            replacer.visit_type_mut(ty);
        }
    }

    let mut output = quote! {};
    if let (Some(trait_name), false) = (&args.trait_name, replacer.names.is_empty()) {
        let impl_ident = &args.impl_ident;
        let projections = replacer.names.iter().map(|(name, params, args)| {
            let capture = type_capture_ident(trait_name, name);
            let args = quote!(#(#args),*);
            (
                quote!(type #name<#(#params),*>;),
                quote!(type #name<#(#params),*> = __T::#capture<#args>;),
                quote! {
                    #[allow(non_camel_case_types)]
                    pub type #name<#(#params),*> =
                        <super::#impl_ident as super::#local_ident>::#name<#args>;
                },
            )
        });
        let (decls, impls, aliases): (Vec<_>, Vec<_>, Vec<_>) = projections.multiunzip();
        output.extend(quote! {
            #[doc(hidden)]
            #[allow(non_camel_case_types)]
            pub trait #local_ident {
                #(#decls)*
            }
            impl<__T: #trait_ident> #local_ident for __T {
                #(#impls)*
            }
            #[doc(hidden)]
            #[allow(non_snake_case)]
            pub mod #types_ident {
                #(#aliases)*
            }
        });
    }
    output.extend(derive_pub_fns(
        &args.crate_path,
        &impl_ty,
        &fns,
        Some(trait_ident),
        &args.client_name,
    ));
    output.extend(derive_fns_spec(
        &args.crate_path,
        &args.spec_name,
        &fns,
        spec_export,
    ));
    output.extend(derive_client_impl(
        &args.crate_path,
        &args.client_name,
        &fns,
    ));
    output.extend(derive_args_impl(&args.args_name, &fns));
    output.extend(derive_contract_function_registration_ctor(
        &args.crate_path,
        &impl_ty,
        Some(trait_ident),
        &fns,
    ));

    Ok(output)
}

fn cfg_condition(attrs: &[Attribute]) -> Result<Option<TokenStream2>, Error> {
    let cfgs = attrs
        .iter()
        .filter(|attr| attr.path().is_ident("cfg"))
        .map(|attr| attr.parse_args::<TokenStream2>().map_err(Error::from))
        .collect::<Result<Vec<_>, Error>>()?;

    Ok(match cfgs.as_slice() {
        [] => None,
        [cfg] => Some(quote! { #cfg }),
        _ => Some(quote! { all(#(#cfgs),*) }),
    })
}

/// Replaces placeholder paths, e.g. `__contracttrait_type::Vec<..>`, with the
/// alias of the same name in the local module, collecting the names and the
/// parameters each alias needs for the arguments it is given.
struct ReplaceTypePlaceholders {
    local: TokenStream2,
    names: Vec<(Ident, Vec<TokenStream2>, Vec<Ident>)>,
}

impl VisitMut for ReplaceTypePlaceholders {
    fn visit_type_mut(&mut self, ty: &mut Type) {
        if let Type::Path(TypePath { qself: None, path }) = ty {
            if let [root, name] = path.segments.iter().collect::<Vec<_>>()[..] {
                if root.ident == TYPE_PLACEHOLDER {
                    let ident = name.ident.clone();
                    if !self.names.iter().any(|(n, _, _)| *n == ident) {
                        let (params, args) = match &name.arguments {
                            PathArguments::AngleBracketed(args) => args
                                .args
                                .iter()
                                .enumerate()
                                .map(|(i, a)| match a {
                                    GenericArgument::Type(_) => {
                                        let p = format_ident!("T{i}");
                                        (quote!(#p), p)
                                    }
                                    _ => {
                                        let p = format_ident!("N{i}");
                                        (quote!(const #p: usize), p)
                                    }
                                })
                                .unzip(),
                            _ => (Vec::new(), Vec::new()),
                        };
                        self.names.push((ident, params, args));
                    }
                    let local = &self.local;
                    path.segments[0] = syn::parse_quote!(#local);
                }
            }
        }
        syn::visit_mut::visit_type_mut(self, ty);
    }
}
