// Command genhost generates the Go bindings for the Soroban host functions
// from the env.json interface definition in rs-soroban-env.
//
// Every host function takes and returns 64-bit values on the wasm ABI, so
// every binding takes and returns uint64 (or int64 for raw i64 values).
//
// Usage:
//
//	go run ./internal/genhost -env internal/genhost/env.json -out soroban/internal/host
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

type envJSON struct {
	Modules []struct {
		Name      string `json:"name"`
		Export    string `json:"export"`
		Functions []struct {
			Export string `json:"export"`
			Name   string `json:"name"`
			Args   []struct {
				Name string `json:"name"`
				Type string `json:"type"`
			} `json:"args"`
			Return      string `json:"return"`
			Docs        string `json:"docs"`
			MinProtocol *int   `json:"min_supported_protocol"`
			MaxProtocol *int   `json:"max_supported_protocol"`
		} `json:"functions"`
	} `json:"modules"`
}

func main() {
	envPath := flag.String("env", "internal/genhost/env.json", "path to env.json")
	out := flag.String("out", "soroban/internal/host", "output directory")
	flag.Parse()

	data, err := os.ReadFile(*envPath)
	if err != nil {
		fatal(err)
	}
	var env envJSON
	if err := json.Unmarshal(data, &env); err != nil {
		fatal(err)
	}

	var wasm, stub bytes.Buffer
	header := "// Code generated by internal/genhost from env.json. DO NOT EDIT.\n\n"
	wasm.WriteString(header + "//go:build tinygo.wasm\n\npackage host\n\n")
	stub.WriteString(header + "//go:build !tinygo.wasm\n\npackage host\n\n")

	for _, m := range env.Modules {
		if m.Name == "test" {
			// Test-only functions are not callable from contracts.
			continue
		}
		fmt.Fprintf(&wasm, "// Module %q (%s).\n\n", m.Name, m.Export)
		for _, f := range m.Functions {
			if f.MaxProtocol != nil {
				continue
			}
			name := camel(f.Name)
			var params []string
			var names []string
			for _, a := range f.Args {
				params = append(params, fmt.Sprintf("%s %s", safeIdent(a.Name), goType(a.Type)))
				names = append(names, safeIdent(a.Name))
			}
			ret := goType(f.Return)
			doc := strings.TrimSpace(f.Docs)
			var docLines string
			for _, l := range strings.Split(doc, "\n") {
				docLines += "// " + strings.TrimRight(l, " ") + "\n"
			}
			argSig := describeArgs(f.Args)
			docLines += fmt.Sprintf("//\n// Host: %s.%s %s(%s) -> %s", m.Export, f.Export, f.Name, argSig, f.Return)
			if f.MinProtocol != nil {
				docLines += fmt.Sprintf(" (protocol >= %d)", *f.MinProtocol)
			}
			docLines += "\n"
			fmt.Fprintf(&wasm, "%s//go:wasmimport %s %s\nfunc %s(%s) %s\n\n", docLines, m.Export, f.Export, name, strings.Join(params, ", "), ret)
			fmt.Fprintf(&stub, "%sfunc %s(%s) %s { panic(notInContract) }\n\n", docLines, name, joinUnderscore(params), ret)
			_ = names
		}
	}
	stub.WriteString("const notInContract = \"soroban: host functions are only available when compiled to a contract with soroban-go build\"\n")

	write(filepath.Join(*out, "host_imports.go"), wasm.Bytes())
	write(filepath.Join(*out, "host_stub.go"), stub.Bytes())
}

func describeArgs(args []struct {
	Name string `json:"name"`
	Type string `json:"type"`
}) string {
	var s []string
	for _, a := range args {
		s = append(s, a.Name+": "+a.Type)
	}
	return strings.Join(s, ", ")
}

// joinUnderscore renames all params to _ in stubs to avoid unused warnings
// in linters while keeping the types visible.
func joinUnderscore(params []string) string {
	var s []string
	for _, p := range params {
		parts := strings.SplitN(p, " ", 2)
		s = append(s, "_ "+parts[1])
	}
	return strings.Join(s, ", ")
}

func goType(t string) string {
	switch t {
	case "i64":
		return "int64"
	default:
		return "uint64"
	}
}

func camel(s string) string {
	var b strings.Builder
	for _, p := range strings.Split(s, "_") {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func safeIdent(s string) string {
	switch s {
	case "func", "map", "type", "range", "string", "len":
		return s + "_"
	}
	return s
}

func write(path string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		fatal(fmt.Errorf("%s: %w\n%s", path, err, src))
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "genhost:", err)
	os.Exit(1)
}
