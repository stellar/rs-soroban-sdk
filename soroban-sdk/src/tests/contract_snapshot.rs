use crate::{self as soroban_sdk};
use soroban_sdk::{contract, contractimpl, xdr, Address, Env, TryFromVal};

#[contract]
pub struct Contract;

#[contractimpl]
impl Contract {
    pub fn store(env: Env, k: i32, v: i32) {
        env.storage().persistent().set(&k, &v)
    }
    pub fn get(env: Env, k: i32) -> i32 {
        env.storage().persistent().get(&k).unwrap()
    }
}

#[test]
fn test() {
    let e = Env::default();
    let contract_id = e.register(Contract, ());
    let contract_id_xdr = xdr::ScAddress::try_from(&contract_id).unwrap();
    let client = ContractClient::new(&e, &contract_id);

    client.store(&2, &4);
    assert_eq!(client.get(&2), 4);

    let snapshot = e.to_ledger_snapshot();

    let e = Env::from_ledger_snapshot(snapshot);
    let contract_id = Address::try_from_val(&e, &contract_id_xdr).unwrap();
    e.register_at(&contract_id, Contract, ());
    let client = ContractClient::new(&e, &contract_id);

    assert_eq!(client.get(&2), 4);
}

#[test]
fn test_from_snapshot_with_zero_protocol_version() {
    let mut snapshot = soroban_ledger_snapshot::LedgerSnapshot::default();
    snapshot.protocol_version = 0; // Simulate snapshot generated by older stellar-cli
    let e = Env::from_ledger_snapshot(snapshot);
    let contract_id = e.register(Contract, ());
    let client = ContractClient::new(&e, &contract_id);
    client.store(&2, &4);
    assert_eq!(client.get(&2), 4);
}

#[test]
fn test_from_snapshot_file_with_zero_protocol_version() {
    let temp_dir = std::env::temp_dir();
    let temp_snapshot_file = temp_dir.join("test_zero_protocol_snapshot.json");
    let old_snapshot_json = r#"{
      "protocol_version": 0,
      "sequence_number": 54463359,
      "timestamp": 0,
      "network_id": "7ac33997544e3175d266bd022439b22cdb16508c01163f26e5cb2a3e1045a979",
      "base_reserve": 1,
      "min_persistent_entry_ttl": 0,
      "min_temp_entry_ttl": 0,
      "max_entry_ttl": 0,
      "ledger_entries": []
    }"#;
    std::fs::write(&temp_snapshot_file, old_snapshot_json).unwrap();

    let e = Env::from_ledger_snapshot_file(&temp_snapshot_file);
    let contract_id = e.register(Contract, ());
    let client = ContractClient::new(&e, &contract_id);
    client.store(&10, &20);
    assert_eq!(client.get(&10), 20);

    let _ = std::fs::remove_file(temp_snapshot_file);
}
