impl_spec_anchor_for_tuple!(T0, T1);
impl_spec_anchor_for_tuple!(T0, T1, T2);
impl_spec_anchor_for_tuple!(T0, T1, T2, T3);
impl_spec_anchor_for_tuple!(T0, T1, T2, T3, T4);
