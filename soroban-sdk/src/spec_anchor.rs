impl_spec_anchor_for_tuple!(T0, T1, T2, T3, T4, T5, T6, T7, T8);
impl_spec_anchor_for_tuple!(T0, T1, T2, T3, T4, T5, T6, T7, T8, T9);
impl_spec_anchor_for_tuple!(T0, T1, T2, T3, T4, T5, T6, T7, T8, T9, T10);
