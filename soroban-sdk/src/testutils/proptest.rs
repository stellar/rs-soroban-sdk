//! Support for property testing Soroban contracts with [`proptest`].
//!
//! Property tests generate Soroban contract types with the prototype pattern
//! that the [`arbitrary`] module defines for fuzzing: because every
//! [`SorobanArbitrary::Prototype`] implements [`Arbitrary`], the same values
//! that feed a fuzzer can feed a `proptest` property test, which runs as an
//! ordinary `#[test]` under `cargo test`, with no fuzzing toolchain.
//!
//! [`proptest`]: https://docs.rs/proptest
//! [`arbitrary`]: crate::testutils::arbitrary
//! [`SorobanArbitrary::Prototype`]: crate::testutils::arbitrary::SorobanArbitrary::Prototype
//! [`Arbitrary`]: ::arbitrary::Arbitrary
//!
//!
//! ## Bridging `Arbitrary` to a `Strategy`
//!
//! `proptest` generates values from [`Strategy`]s, not from `Arbitrary`
//! implementations, so the two are bridged by the
//! [`proptest-arbitrary-interop`] crate: its `arb` function turns an
//! `Arbitrary` type into a `Strategy`. The pattern is the same as for fuzzing
//! — generate the prototype, then convert it to the `Env`-hosted contract type
//! with `into_val` inside the test body, where an [`Env`] is available.
//!
//! When a property fails, `proptest` normally shrinks the failing input: it
//! retries the test with progressively simpler versions of the value, so that
//! what it finally reports is the smallest input it could find that still
//! fails. Shrinking is degraded across this bridge, because `arb` simplifies by
//! truncating the generated bytes and building a new value from them rather
//! than by reducing the value itself. The input `proptest` reports still fails
//! the property, but it is generally a different input rather than a smaller
//! version of the one that failed first.
//!
//! Property testing a contract this way needs both crates as dev-dependencies:
//!
//! ```toml
//! [dev-dependencies]
//! proptest = "1"
//! proptest-arbitrary-interop = "0.1"
//! ```
//!
//! [`Strategy`]: https://docs.rs/proptest/latest/proptest/strategy/trait.Strategy.html
//! [`proptest-arbitrary-interop`]: https://docs.rs/proptest-arbitrary-interop
//! [`Env`]: crate::Env
//!
//!
//! ## Example: generate an `Address` in a property test
//!
//! ```
//! use proptest::prelude::*;
//! use proptest_arbitrary_interop::arb;
//! use soroban_sdk::testutils::arbitrary::SorobanArbitrary;
//! use soroban_sdk::{Address, Env, IntoVal};
//!
//! proptest! {
//!     #[test]
//!     fn test_deposit(
//!         address_proto in arb::<<Address as SorobanArbitrary>::Prototype>(),
//!         deposit_amount in 0i128..=i128::MAX,
//!     ) {
//!         let env = Env::default();
//!         let address: Address = address_proto.into_val(&env);
//!         // call the contract with `address` and `deposit_amount`
//!     }
//! }
//! # fn main() { }
//! ```
//!
//! Note that generated `Address` prototypes always convert to contract
//! addresses, never to account (`G...`) addresses. A property test that also
//! needs account addresses must construct them itself with
//! `Address::from_str`.
//!
//!
//! ## Example: generate a custom contract type in a property test
//!
//! ```
//! use proptest::prelude::*;
//! use proptest_arbitrary_interop::arb;
//! use soroban_sdk::testutils::arbitrary::SorobanArbitrary;
//! use soroban_sdk::{contracttype, Address, Env, IntoVal};
//!
//! #[contracttype]
//! pub struct Claim {
//!     pub claimant: Address,
//!     pub amount: i128,
//! }
//!
//! proptest! {
//!     #[test]
//!     fn test_claim(claim_proto in arb::<<Claim as SorobanArbitrary>::Prototype>()) {
//!         let env = Env::default();
//!         let claim: Claim = claim_proto.into_val(&env);
//!         // call the contract with `claim`
//!     }
//! }
//! # fn main() { }
//! ```
